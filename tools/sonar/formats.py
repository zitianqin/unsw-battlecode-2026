"""Writes the listener's per-team sonar format table (listen_formats.hpp in the bot folder, read by its listen.hpp) from
tools/sonar/spec.toml, with tools/sonar/measured.json's measurements folded in.

The spec holds one [[format]] per team per protocol version (never delete an old version: a team may bring any of
them to a tournament), each with its layouts (recogniser bits and fields) and where it came from; verify.py measures
every entry on replays and writes `cover`, `stray`, `detects` and `verified` to measured.json. Adding a team or a
version is a spec edit (or refresh.py) and a rerun:

    .venv/bin/python tools/sonar/formats.py [--bot DIR]            # write DIR/listen_formats.hpp (default bot/)
    .venv/bin/python tools/sonar/formats.py [--bot DIR] --check    # exit 1 if it is out of date with the spec
"""

from __future__ import annotations

import argparse
import json
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
SPEC = HERE / "spec.toml"
MEASURED = HERE / "measured.json"  # verify.py --update: cover, stray, detects, verified per "team/version"
BOT = REPO / "bot"
FIELDS = ("x", "y", "tile", "length", "round", "id")
MAX_LAYOUTS = 3
KINDS = ("report", "keyed", "token", "silent")


# The spec's formats with their measurements (MEASURED, keyed "team/version") folded in, checked: known kind, at most
# MAX_LAYOUTS layouts, fields inside 64 bits and clear of the recogniser's bits, x and y together or a tile instead.
# Raises ValueError naming the entry.
def load(path: Path = SPEC, measured: Path = MEASURED) -> list[dict]:
    formats = tomllib.loads(path.read_text())["format"]
    found = json.loads(measured.read_text()) if measured.exists() else {}
    seen = set()
    for f in formats:
        name = f"{f.get('team')}/{f.get('version')}"
        for key in ("cover", "stray", "detects", "verified"):
            if key in found.get(name, {}):
                f[key] = found[name][key]
        if name in seen:
            raise ValueError(f"{name}: duplicate team and version")
        seen.add(name)
        if f.get("kind") not in KINDS:
            raise ValueError(f"{name}: kind must be one of {KINDS}")
        layouts = f.get("layout", [])
        if len(layouts) > MAX_LAYOUTS:
            raise ValueError(f"{name}: at most {MAX_LAYOUTS} layouts")
        if f["kind"] != "report" and layouts and f["kind"] != "keyed":
            raise ValueError(f"{name}: only report and keyed formats have layouts")
        for layout in layouts:
            mask, value = int(layout["mask"], 16), int(layout["value"], 16)
            if value & ~mask:
                raise ValueError(f"{name}: value has bits outside the mask")
            if int(layout.get("flip", "0x0"), 16) & mask:
                raise ValueError(f"{name}: flip touches the recogniser's bits")
            taken = mask
            for key in FIELDS:
                if key not in layout:
                    continue
                shift, bits = layout[key]
                span = ((1 << bits) - 1) << shift
                if shift + bits > 64 or span & taken:
                    raise ValueError(f"{name}: field {key} overlaps the recogniser or another field")
                taken |= span
            if ("x" in layout) != ("y" in layout) or ("tile" in layout and "x" in layout):
                raise ValueError(f"{name}: a layout has x and y, or a tile")
    return formats


def cpp_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def field(layout: dict, key: str) -> str:
    shift, bits = layout.get(key, (0, 0))
    return f"{{{shift}, {bits}}}"


def layout_cpp(layout: dict) -> str:
    fields = ", ".join(f".{key} = {field(layout, key)}" for key in FIELDS)
    return (f"{{.mask = {layout['mask']}ULL, .value = {layout['value']}ULL, .flip = {layout.get('flip', '0x0')}ULL, {fields}, "
            f".lag = {layout.get('lag', 0)}, .sighting = {str(layout.get('sighting', False)).lower()}}}")


def format_cpp(f: dict) -> str:
    layouts = f.get("layout", [])
    body = ",\n         ".join(layout_cpp(layout) for layout in layouts)
    return (f"    {{.team = {f['team']}, .name = {cpp_string(f['name'])}, .version = {cpp_string(f['version'])}, "
            f".kind = Kind::{f['kind'].capitalize()}, .detects = {str(f.get('detects', False)).lower()}, "
            f".verified = {str(f.get('verified', False)).lower()},\n"
            f"     .cover = {f.get('cover', 0.0)!r}, .stray = {f.get('stray', 0.0)!r}, .layouts = {len(layouts)},\n"
            f"     .layout = {{{{{body}}}}}}},")


def render(formats: list[dict]) -> str:
    rows = "\n".join(format_cpp(f) for f in formats)
    return f"""#pragma once

// Generated by tools/sonar/formats.py from tools/sonar/spec.toml and measured.json (tools/sonar/README.md); edit
// the spec or rerun tools/sonar/refresh.py, never this file.
// One row per team per protocol version (listen.hpp says how the listener reads it).

#include <array>
#include <cstdint>

namespace bot::listen {{

// Bits [shift, shift + bits) of a heard value; bits 0 when the layout has no such field.
struct Field {{
    int shift = 0, bits = 0;
}};

// One message type of a format: a value is of it when (value & mask) == value, and its fields are in range; the
// fields are read after XORing the value with `flip` (a team that masks its fields with a constant). A tile is
// y * width + x. `lag` is how many rounds old a report without a round field is. A sighting layout
// reports one of the sender's enemies (our dragons), not the sender's own.
struct Layout {{
    std::uint64_t mask = 0, value = 0, flip = 0;
    Field x, y, tile, length, round, id;
    int lag = 0;
    bool sighting = false;
}};

// Report: plain fields we decode. Keyed: a cipher or keyed hash (no fields; a recogniser when one is known).
// Token: a small vocabulary of opaque values. Silent: sends nothing.
enum class Kind {{ Report, Keyed, Token, Silent }};

// A team's protocol version. `cover` is the share of the team's values its layouts recognise and `stray` the share
// of the most confusable other team's values in one game they recognise (tools/sonar/verify.py measures both).
// `detects`: its recogniser names the team (cover 0.3 or more and at least 4 times stray, on 50 values or more);
// `verified`: its decoded heads matched the replays' true state at 95% or more.
struct Format {{
    int team = 0;
    char const* name = "";
    char const* version = "";
    Kind kind = Kind::Report;
    bool detects = false;
    bool verified = false;
    double cover = 0, stray = 0;
    int layouts = 0;
    std::array<Layout, {MAX_LAYOUTS}> layout{{}};
}};

inline constexpr std::array FORMATS = std::to_array<Format>({{
{rows}
}});

}} // namespace bot::listen
"""


# One spec entry as TOML text, in the spec's key order (layouts last), for appending new versions.
def entry_toml(entry: dict) -> str:
    lines = ["[[format]]"]
    for key in ("team", "name", "version", "kind", "source", "note"):
        if key in entry:
            lines.append(f"{key} = {json.dumps(entry[key], ensure_ascii=False)}")
    for layout in entry.get("layout", []):
        lines.append("  [[format.layout]]")
        for key, value in layout.items():
            if isinstance(value, bool):
                lines.append(f"  {key} = {str(value).lower()}")
            elif isinstance(value, (list, tuple)):
                lines.append(f"  {key} = [{value[0]}, {value[1]}]")
            elif isinstance(value, int):
                lines.append(f"  {key} = {value}")
            else:
                lines.append(f"  {key} = {json.dumps(value)}")
    return "\n".join(lines) + "\n"


# Appends `entries` to the spec, refusing a team and version it already has.
def append(entries: list[dict], path: Path = SPEC) -> None:
    have = {(f["team"], f["version"]) for f in load(path)}
    for e in entries:
        if (e["team"], e["version"]) in have:
            raise ValueError(f"{e['team']}/{e['version']} is already in the spec")
    with path.open("a") as out:
        for e in entries:
            out.write("\n" + entry_toml(e))
    load(path)


# Writes the header into `bot` (a bot folder with listen.hpp), or with `check` only compares; True when it matches.
def write(bot: Path = BOT, check: bool = False) -> bool:
    header, text = bot / "listen_formats.hpp", render(load())
    if check:
        return header.exists() and header.read_text() == text
    header.write_text(text)
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--bot", type=Path, default=BOT, help="the bot folder to write listen_formats.hpp into")
    parser.add_argument("--check", action="store_true", help="fail if the header does not match the spec")
    args = parser.parse_args()
    if args.check:
        if not write(args.bot, check=True):
            print(f"{args.bot / 'listen_formats.hpp'} is out of date: run tools/sonar/formats.py", file=sys.stderr)
            return 1
        return 0
    write(args.bot)
    print(f"wrote {args.bot / 'listen_formats.hpp'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
